    public void loadBan()
{
    cboBan.removeAllItems();

    cboBan.addItem("-- Chọn bàn --");

    try
    {
        Connection con =
                DBConnect.getConnection();

        String sql =
                "SELECT SoBan "
              + "FROM BanAn";

        PreparedStatement ps =
                con.prepareStatement(sql);

        ResultSet rs =
                ps.executeQuery();

        while(rs.next())
        {
            cboBan.addItem(
                    rs.getString("SoBan")
            );
        }
    }
    catch(Exception e)
    {
        e.printStackTrace();
    }
}
    public void addFoodBar(
        FoodBar item)
{
    pnlContainer.add(item);

    pnlContainer.revalidate();

    pnlContainer.repaint();

    capNhatTongTien();
}
    public void resetHoaDon()
{
    pnlContainer.removeAll();

    pnlContainer.revalidate();
    pnlContainer.repaint();

    cboBan.setSelectedItem("--");
    lblTongTien.setText("0 đ");
}
public void capNhatTongTien()
{
    double tong = 0;

    for(Component c :
            pnlContainer.getComponents())
    {
        if(c instanceof FoodBar)
        {
            FoodBar item =
                    (FoodBar)c;

            tong +=
                    item.getTongTien();
        }
    }

    lblTongTien.setText(
            String.format(
                    "%,.0f đ",
                    tong
            )
    );
}

    public void clearHoaDon()
{
    pnlContainer.removeAll();

    pnlContainer.revalidate();

    pnlContainer.repaint();
}
