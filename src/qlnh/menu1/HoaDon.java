    private void btnThanhToanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThanhToanActionPerformed
        try
    {
        if(pnlContainer.getComponentCount() == 0)
        {
            JOptionPane.showMessageDialog(
                    this,
                    "Chưa chọn món!"
            );

            return;
        }

        if(cboBan.getSelectedIndex() == 0)
        {
            JOptionPane.showMessageDialog(
                    this,
                    "Vui lòng chọn bàn!"
            );

            return;
        }

        Connection con =
                (Connection) DBConnect.getConnection();

        StringBuilder dsMon =
                new StringBuilder();

        double tongTien = 0;

        for(Component c :
                pnlContainer.getComponents())
        {
            if(c instanceof FoodBar)
            {
                FoodBar item =
                        (FoodBar)c;

                dsMon.append(
                        item.getTenMon()
                );

                dsMon.append(
                        " x "
                );

                dsMon.append(
                        item.getSoLuong()
                );

                dsMon.append("; ");

                tongTien +=
                        item.getTongTien();
            }
        }

        String sql =
                "INSERT INTO HOADON "
              + "(SOBAN,MANV,DSMON,NGAYLAP,TONGTIEN)"
              + " VALUES(?,?,?,GETDATE(),?)";

        PreparedStatement ps =
                con.prepareStatement(sql);

        ps.setInt(
                1,
                Integer.parseInt(
                        cboBan
                        .getSelectedItem()
                        .toString()
                )
        );

        ps.setInt(
                2,
                Session.maNV
        );

        ps.setString(
                3,
                dsMon.toString()
        );

        ps.setDouble(
                4,
                tongTien
        );

        ps.executeUpdate();

        JOptionPane.showMessageDialog(
                this,
                "Thanh toán thành công!"
        );

        pnlContainer.removeAll();

        pnlContainer.revalidate();

        pnlContainer.repaint();

        lblTongTien.setText("0 đ");

        cboBan.setSelectedIndex(0);

        Menu.instance.resetKhachHang();
    }
    catch(Exception e)
    {
        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                e.getMessage()
        );
    }
    }//GEN-LAST:event_btnThanhToanActionPerformed

