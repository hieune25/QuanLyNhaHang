    public void addFoodBar(
        String tenMon,
        double gia,
        int soLuong)
{
    for(Component c :
            pnlContainer.getComponents())
    {
        if(c instanceof FoodBar)
        {
            FoodBar item =
                    (FoodBar)c;

            if(item.getTenMon()
                   .equals(tenMon))
            {
                item.tangSoLuong();

                capNhatTongTien();

                return;
            }
        }
    }

    FoodBar item =
            new FoodBar(
                    1,
                    tenMon,
                    gia
            );

    pnlContainer.add(item);

    pnlContainer.revalidate();

    pnlContainer.repaint();

    capNhatTongTien();
    loadBan();
}


    

