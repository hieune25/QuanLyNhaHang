    private void lblDangNhapMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_lblDangNhapMouseClicked
    String username = txtDangNhap.getText().trim();
    String password = String.valueOf(txtMatKhau.getPassword());

    // Kiểm tra rỗng
    if(username.isEmpty() || password.isEmpty()){
        JOptionPane.showMessageDialog(
                this,
                "Vui lòng nhập đầy đủ tài khoản và mật khẩu!"
        );
        return;
    }

    String sql = "SELECT * FROM TAIKHOAN "
               + "WHERE TENDANGNHAP = ? AND MATKHAU = ?";

    try {

        Connection conn = DBConnect.getConnection();

        PreparedStatement ps = conn.prepareStatement(sql);

        ps.setString(1, username);
        ps.setString(2, password);

        ResultSet rs = ps.executeQuery();

        if(rs.next())
{
    Session.maNV =
            rs.getInt("MANV");

    Session.tenDangNhap =
            rs.getString("TENDANGNHAP");

    Session.vaiTro =
            rs.getString("VAITRO");

    String vaiTro =
            rs.getString("VAITRO");

    JOptionPane.showMessageDialog(
            this,
            "Đăng nhập thành công!"
    );

    if(vaiTro.equalsIgnoreCase("QuanLy"))
    {
        new menuql().setVisible(true);
    }
    else if(vaiTro.equalsIgnoreCase("NhanVien"))
    {
        new Menu().setVisible(true);
    }

    this.dispose();
}
else
{
    JOptionPane.showMessageDialog(
            this,
            "Tài khoản hoặc mật khẩu không đúng!"
    );
}

    } catch (HeadlessException | SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Lỗi kết nối cơ sở dữ liệu!"
        );

    }
    }//GEN-LAST:event_lblDangNhapMouseClicked

